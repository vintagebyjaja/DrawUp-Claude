-- DrawUp v29 Zero-credit help + smart navigation (migration 0074, SQL v29-01).
-- Additive and safe to run twice. Nothing existing is dropped or changed.
--  * help_registry: the founder's changes to the built-in help registry (status, note, answer text, extra phrases,
--    hidden). The routes themselves live in the code and cannot be changed here, so a published row can never point
--    a member at a page that does not exist. Everyone can read it (the help answers use it); only HQ can write it.
--    A row is a draft until HQ publishes it; publishing a feature as live or limited needs a passing route check
--    (validation.ok = true), which HQ › Help registry runs in the browser against the real menu before publishing.
--  * help_log: one row per free help answer (what was asked, which feature answered). Members add their own rows;
--    only HQ reads them.

create table if not exists public.help_registry (
  feature_id text primary key check (feature_id ~ '^[a-z0-9-]{2,60}$'),
  draft jsonb not null default '{}'::jsonb,
  published jsonb,
  validation jsonb,
  published_at timestamptz,
  published_by uuid references public.profiles(id) on delete set null,
  updated_at timestamptz not null default now(),
  updated_by uuid references public.profiles(id) on delete set null
);

create or replace function public.help_registry_guard() returns trigger language plpgsql as $$
declare p jsonb := new.published; s text;
begin
  new.updated_at := now();
  new.updated_by := auth.uid();
  if p is null then return new; end if;
  if jsonb_typeof(p) <> 'object' then raise exception 'published must be an object'; end if;
  s := p->>'status';
  if s is not null and s not in ('live', 'limited', 'building', 'season2', 'off') then raise exception 'unknown status %', s; end if;
  if length(coalesce(p->>'note', '')) > 600 or length(coalesce(p->>'answer', '')) > 600 then raise exception 'note and answer are limited to 600 characters'; end if;
  if p ? 'aliases' and (jsonb_typeof(p->'aliases') <> 'array' or jsonb_array_length(p->'aliases') > 30) then raise exception 'aliases must be a list of up to 30 phrases'; end if;
  if s in ('live', 'limited') and coalesce((new.validation->>'ok')::boolean, false) is not true then
    raise exception 'Run the route check before publishing % as %', new.feature_id, s;
  end if;
  if tg_op = 'INSERT' or old.published is distinct from new.published then
    new.published_at := now();
    new.published_by := auth.uid();
  end if;
  return new;
end $$;
drop trigger if exists help_registry_guard on public.help_registry;
create trigger help_registry_guard before insert or update on public.help_registry for each row execute function public.help_registry_guard();

alter table public.help_registry enable row level security;
drop policy if exists "help registry read" on public.help_registry;
create policy "help registry read" on public.help_registry for select using (true);
drop policy if exists "help registry hq insert" on public.help_registry;
create policy "help registry hq insert" on public.help_registry for insert with check (public.is_drawup_admin());
drop policy if exists "help registry hq update" on public.help_registry;
create policy "help registry hq update" on public.help_registry for update using (public.is_drawup_admin()) with check (public.is_drawup_admin());
drop policy if exists "help registry hq delete" on public.help_registry;
create policy "help registry hq delete" on public.help_registry for delete using (public.is_drawup_admin());
grant select on public.help_registry to anon, authenticated;
grant insert, update, delete on public.help_registry to authenticated;

create table if not exists public.help_log (
  id bigint generated by default as identity primary key,
  user_id uuid references public.profiles(id) on delete cascade,
  surface text not null default 'unknown',
  question text not null check (length(question) <= 300),
  feature_id text,
  kind text not null default 'answer',
  thread_id uuid,
  created_at timestamptz not null default now()
);
create index if not exists help_log_recent_idx on public.help_log (created_at desc);
create index if not exists help_log_feature_idx on public.help_log (feature_id, created_at desc);

alter table public.help_log enable row level security;
drop policy if exists "help log own insert" on public.help_log;
create policy "help log own insert" on public.help_log for insert with check (user_id = auth.uid());
drop policy if exists "help log hq read" on public.help_log;
create policy "help log hq read" on public.help_log for select using (public.is_drawup_admin());
drop policy if exists "help log hq delete" on public.help_log;
create policy "help log hq delete" on public.help_log for delete using (public.is_drawup_admin());
grant select, insert, delete on public.help_log to authenticated;
grant usage on sequence public.help_log_id_seq to authenticated;

