-- DrawUp v28 Visual answers + Watch & Learn videos + legends in the AI Team (migration 0071, SQL v28-01).
-- Additive and safe to run twice. Nothing existing is dropped.
--  * learn_videos: YouTube videos found from members' questions (link, title, channel, thumbnail only; DrawUp never
--    stores or hosts the video). Written only by the server after YouTube confirms the video is real and public.
--    Every signed-in member can read the visible ones in Arch Coach > Learning > Watch & Learn. HQ can hide one.
--  * learn_video_asks: which member asked about which video ("From your questions"). Private to the member.
--  * coach_messages.speaker may now be 'legend' (the member's Hall of Fame legend chiming in on an AI Team chat).

create table if not exists public.learn_videos (
  id uuid primary key default gen_random_uuid(),
  video_id text not null unique check (video_id ~ '^[A-Za-z0-9_-]{11}$'),
  url text not null check (url like 'https://www.youtube.com/watch?v=%'),
  title text not null default 'YouTube video',
  channel_title text,
  channel_url text check (channel_url is null or channel_url = '' or channel_url like 'https://www.youtube.com/%'),
  thumbnail_url text check (thumbnail_url is null or thumbnail_url like 'https://i.ytimg.com/%'),
  topic text,
  topic_key text,
  source text not null default 'ai_answer' check (source in ('ai_answer', 'hq', 'member')),
  hidden boolean not null default false,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  last_asked_at timestamptz not null default now()
);
create index if not exists learn_videos_topic_idx on public.learn_videos (topic_key, last_asked_at desc);
create index if not exists learn_videos_recent_idx on public.learn_videos (hidden, last_asked_at desc);

create table if not exists public.learn_video_asks (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  video_id text not null references public.learn_videos(video_id) on delete cascade,
  question text,
  topic text,
  created_at timestamptz not null default now(),
  constraint learn_video_asks_once unique (user_id, video_id)
);
create index if not exists learn_video_asks_user_idx on public.learn_video_asks (user_id, created_at desc);

alter table public.learn_videos enable row level security;
alter table public.learn_video_asks enable row level security;

drop policy if exists "members read visible learn videos" on public.learn_videos;
create policy "members read visible learn videos" on public.learn_videos for select
  to authenticated using (hidden = false or public.is_drawup_admin());
drop policy if exists "hq hides learn videos" on public.learn_videos;
create policy "hq hides learn videos" on public.learn_videos for update
  to authenticated using (public.is_drawup_admin()) with check (public.is_drawup_admin());

drop policy if exists "members read their own video asks" on public.learn_video_asks;
create policy "members read their own video asks" on public.learn_video_asks for select
  to authenticated using (user_id = auth.uid());
drop policy if exists "members remove their own video asks" on public.learn_video_asks;
create policy "members remove their own video asks" on public.learn_video_asks for delete
  to authenticated using (user_id = auth.uid());

grant select, update on public.learn_videos to authenticated;
grant select, delete on public.learn_video_asks to authenticated;
grant all on public.learn_videos, public.learn_video_asks to service_role;
grant usage, select on all sequences in schema public to service_role;

-- Legends can speak in AI Team threads.
alter table public.coach_messages drop constraint if exists coach_messages_speaker_check;
alter table public.coach_messages add constraint coach_messages_speaker_check
  check (speaker is null or speaker in ('teammate', 'sixth_man', 'coach', 'system', 'legend'));

select 'DONE drawup-v28-01' as status;
